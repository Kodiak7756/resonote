// Generates src/curriculum/curriculum-data.js from a theory-path-curriculum
// workflow output file, and validates every demo/exercise against the app's
// real CHORD_TYPES / SCALE_TYPES / NOTES so nothing can break the renderer.
//   node tools/build-curriculum.cjs <path-to-workflow-output.json>
const fs = require('fs');
const path = require('path');

const srcPath = process.argv[2];
if (!srcPath) { console.error('usage: node tools/build-curriculum.cjs <output.json>'); process.exit(1); }

const obj = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
const cur = obj.result || obj;
if (!cur.units || !cur.placement) { console.error('no {units, placement} in result'); process.exit(1); }

const NOTES = ['C','C#','D','D#','E','F','F#','G','G#','A','A#','B'];
const ENH = { Db:'C#', Eb:'D#', Gb:'F#', Ab:'G#', Bb:'A#', Cb:'B', 'E#':'F', 'B#':'C', Fb:'E' };
const norm = n => ENH[n] || n;
const CHORD = {
  Triads: ['Major','Minor','Dim','Aug','Sus2','Sus4'],
  '7ths': ['Maj7','7 (Dom)','Min7','Dim7','m7♭5','Aug7','mMaj7'],
  Extended: ['Add9','9','Min9','Maj9','6','Min6','6/9','11','Min11','13','Maj13'],
  Altered: ['7♭5','7♯5','7♭9','7♯9','7♯11','7♭13'],
};
const SCALE = {
  Pentatonic: ['Major Pent.','Minor Pent.'],
  Blues: ['Blues Minor','Blues Major'],
  Diatonic: ['Major','Nat. Minor','Harm. Minor','Mel. Minor'],
  Modes: ['Ionian','Dorian','Phrygian','Lydian','Mixolydian','Aeolian','Locrian'],
  Symmetric: ['Whole Tone','Dim (W-H)','Dim (H-W)'],
};
const issues = [];
const ckNote = (n, w) => { if (n == null) return; if (!NOTES.includes(norm(n))) issues.push(`${w}: bad note "${n}"`); };
function ckDemo(d, w) {
  if (!d) return;
  ckNote(d.root, w + '.root');
  if (d.kind === 'chord' && (!CHORD[d.chordCat] || !CHORD[d.chordCat].includes(d.chordType))) issues.push(`${w}: bad chord ${d.chordCat}/${d.chordType}`);
  if (d.kind === 'scale' && (!SCALE[d.scaleCat] || !SCALE[d.scaleCat].includes(d.scaleName))) issues.push(`${w}: bad scale ${d.scaleCat}/${d.scaleName}`);
  if (d.kind === 'note') ckNote(d.note || d.root, w + '.note');
  if (d.kind === 'progression') (d.progression || []).forEach((c, i) => { ckNote(c.root, `${w}.prog${i}`); if (!CHORD[c.cat] || !CHORD[c.cat].includes(c.type)) issues.push(`${w}.prog${i}: bad chord ${c.cat}/${c.type}`); });
}
function ckEx(ex, w) {
  if (ex.kind === 'mcq') { if (!Array.isArray(ex.options)) issues.push(`${w}: mcq no options`); else if (ex.answer < 0 || ex.answer >= ex.options.length) issues.push(`${w}: mcq answer OOR`); if (ex.audio) ckDemo(ex.audio, w + '.audio'); }
  else if (ex.kind === 'ear') { if (!Array.isArray(ex.earOptions)) issues.push(`${w}: ear no opts`); else { if (ex.answer < 0 || ex.answer >= ex.earOptions.length) issues.push(`${w}: ear answer OOR`); ex.earOptions.forEach((o, i) => ckDemo(o.audio, `${w}.earOpt${i}`)); } }
  else if (ex.kind === 'build') { ckNote(ex.root, w + '.root'); if (!Array.isArray(ex.targetIntervals) || !ex.targetIntervals.length) issues.push(`${w}: build no targets`); }
  else if (ex.kind === 'play') { if (ex.targetNote) ckNote(ex.targetNote, w + '.targetNote'); else if (typeof ex.targetIntervalFromRoot === 'number') ckNote(ex.root, w + '.root'); else issues.push(`${w}: play no target`); }
  else issues.push(`${w}: unknown kind ${ex.kind}`);
}
let lessonCount = 0;
cur.units.forEach(u => u.lessons.forEach(l => { lessonCount++; ckDemo(l.teach && l.teach.demo, `${l.id}.teach.demo`); (l.exercises || []).forEach((ex, i) => ckEx(ex, `${l.id}.ex${i}`)); }));
cur.placement.forEach((q, i) => {
  const w = `placement${i}`;
  if (q.kind === 'ear') { if (!q.earOptions) issues.push(`${w}: no earOptions`); else { if (q.answer < 0 || q.answer >= q.earOptions.length) issues.push(`${w}: answer OOR`); q.earOptions.forEach((o, j) => ckDemo(o.audio, `${w}.earOpt${j}`)); } }
  else { if (!q.options) issues.push(`${w}: no options`); else if (q.answer < 0 || q.answer >= q.options.length) issues.push(`${w}: answer OOR`); if (q.audio) ckDemo(q.audio, w + '.audio'); }
});

const header = '// Auto-generated by tools/build-curriculum.cjs from the fact-checked\n'
  + '// theory-path-curriculum workflow. Basics→advanced guitar theory course.\n'
  + '// Do not hand-edit large sections; regenerate from the workflow output.\n\n';
const out = header + 'export const CURRICULUM = ' + JSON.stringify(cur, null, 2) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'curriculum', 'curriculum-data.js'), out, 'utf8');

console.log(`units=${cur.units.length} lessons=${lessonCount} placement=${cur.placement.length}`);
console.log(`VALIDATION ISSUES: ${issues.length}`);
issues.slice(0, 60).forEach(x => console.log('  - ' + x));
